function build(glyphs, height, lineH) {
  const keys = Object.keys(glyphs);
  const info = {};
  let total = 0;
  for (const k of keys) {
    const rows = glyphs[k].split('/');
    const w = rows.reduce((m, r) => Math.max(m, r.length), 0);
    info[k] = { rows, w, x: total };
    total += w + 1;
  }
  const atlas = makeCanvas(total, height), g = ctx2d(atlas);
  g.fillStyle = '#fff';
  for (const k of keys) {
    const { rows, x } = info[k];
    rows.forEach((r, y) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') g.fillRect(x + i, y, 1, 1); });
  }
  return { info, atlas, height, lineH, tinted: new Map(), upper: !glyphs.a };
}

export const FONT = build(MAIN, 8, 10);
export const SMALL = build(TINY, 5, 7);

function tintedAtlas(font, color) {
  let c = font.tinted.get(color);
  if (!c) {
    c = makeCanvas(font.atlas.width, font.atlas.height);
    const g = ctx2d(c);
    g.drawImage(font.atlas, 0, 0);
    g.globalCompositeOperation = 'source-in';
    g.fillStyle = color; g.fillRect(0, 0, c.width, c.height);
    font.tinted.set(color, c);
  }
  return c;
}

export function textWidth(str, font = FONT) {
  let w = 0;
  if (font.upper) str = str.toUpperCase();
  for (const ch of str) { const gl = font.info[ch] || font.info['?']; w += gl.w + 1; }
  return Math.max(0, w - 1);
}

function run(g, font, atlas, str, x, y) {
  for (const ch of str) {
    const gl = font.info[ch] || font.info['?'];
    if (gl.w) g.drawImage(atlas, gl.x, 0, gl.w, font.height, x, y, gl.w, font.height);
    x += gl.w + 1;
  }
}

// opts: color, shadow (hex), outline (hex), align ('left'|'center'|'right'), font
export function drawText(g, str, x, y, opts = {}) {
  const font = opts.font || FONT;
  str = String(str);
  if (font.upper) str = str.toUpperCase();
  x = Math.round(x); y = Math.round(y);
  if (opts.align === 'center') x -= Math.round(textWidth(str, font) / 2);
  else if (opts.align === 'right') x -= textWidth(str, font);
  if (opts.outline) {
    const a = tintedAtlas(font, opts.outline);
    for (let oy = -1; oy <= 1; oy++) for (let ox = -1; ox <= 1; ox++) if (ox || oy) run(g, font, a, str, x + ox, y + oy);
    if (opts.shadow) run(g, font, a, str, x, y + 2), run(g, font, a, str, x + 1, y + 2), run(g, font, a, str, x - 1, y + 2);
  } else if (opts.shadow) {
    run(g, font, tintedAtlas(font, opts.shadow), str, x, y + 1);
  }
  run(g, font, tintedAtlas(font, opts.color || '#f6f8f4'), str, x, y);
  return x + textWidth(str, font);
}

export function wrapText(str, maxW, font = FONT) {
  const out = [];
  for (const para of str.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t, font) > maxW && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
}
