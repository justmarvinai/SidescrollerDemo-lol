// ------------------------------------------------------------------ the Gloomroot
const BOSS_W = 96, BOSS_H = 84;
const BK = [C.ink, C.n1, C.b1, C.b2, C.b3, C.b4];

function bossBody(eyeOpen, glow) {
  const p = new Pix(BOSS_W, BOSS_H);
  const cx = 48, base = BOSS_H - 1;
  const half = (j) => {
    // j = px above the ground
    const t = j / 58;
    let w = lerp(27, 17, Math.pow(clamp(t, 0, 1), 0.6));
    if (j < 9) w += (9 - j) * (9 - j) * 0.16;
    if (t > 0.8) w += (t - 0.8) * 22;
    return w;
  };
  for (let j = 0; j <= 60; j++) {
    const y = base - j, hw = half(j);
    const wob = Math.round(Math.sin(j * 0.13) * 1.5);
    for (let dx = -Math.round(hw); dx <= Math.round(hw); dx++) {
      const x = cx + dx + wob, u = (dx + hw) / (hw * 2);
      // jagged, hollow crown
      if (j > 50) {
        const tooth = 60 - Math.abs(((dx + 60) % 9) - 4) * 2.2 - hash((dx + 60) / 9 | 0, 2, 7) * 6;
        if (j > tooth) continue;
      }
      let k = u < 0.1 ? 5 : u < 0.3 ? 4 : u < 0.62 ? 3 : u < 0.88 ? 2 : 1;
      const col = dx + Math.round(Math.sin(j * 0.09 + dx * 0.3) * 1.5);
      const streak = hash(col, Math.floor((j + hash(col, 1, 3) * 11) / 7), 5);
      if (streak < 0.34) k--; else if (streak > 0.93) k++;
      if (noise2(dx * 0.2, j * 0.09, 12) > 0.7) k--;
      p.set(x, y, BK[clamp(k, 1, 5)]);
    }
  }
  // roots sprawling along the ground
  const root = (dir, len, thick, seed) => {
    for (let i = 0; i < len; i++) {
      const t = i / len, x = cx + dir * (22 + i), y = base - Math.round(Math.sin(t * Math.PI) * 3 + (1 - t) * 5) + (hash(i >> 2, seed) < 0.3 ? 1 : 0);
      const th = Math.max(1, Math.round(thick * (1 - t)));
      for (let k = 0; k < th + 2; k++) p.set(x, Math.min(base, y + k), k === 0 ? BK[dir < 0 ? 5 : 4] : k < th ? BK[3] : BK[2]);
    }
  };
  root(-1, 22, 5, 1); root(1, 22, 5, 2); root(-1, 14, 7, 3); root(1, 15, 7, 4);

  // antler branches with a few corrupted leaves
  const branch = (bx, by, ang, len, w, depth) => {
    const ex = bx + Math.cos(ang) * len, ey = by - Math.sin(ang) * len;
    p.line(bx, by, ex, ey, BK[3], Math.max(1, Math.round(w)));
    if (w >= 2) p.line(bx - 1, by - 1, ex - 1, ey - 1, BK[5], 1);
    if (depth > 0) { branch(ex, ey, ang + 0.55, len * 0.62, w * 0.6, depth - 1); branch(ex, ey, ang - 0.5, len * 0.55, w * 0.6, depth - 1); }
    else {
      for (const [ox, oy] of [[0, 0], [2, -1], [-2, 1], [1, 2]]) {
        p.set(ex + ox, ey + oy, C.p4); p.set(ex + ox + 1, ey + oy, C.p3); p.set(ex + ox, ey + oy - 1, C.p5);
      }
    }
  };
  branch(cx - 17, base - 55, 2.1, 15, 3.4, 2);
  branch(cx + 17, base - 55, 1.05, 15, 3.4, 2);
  branch(cx - 4, base - 54, 1.75, 9, 2, 1);

  // corruption veins that pulse
  const vein = (sx, sy, len, seed, dirx) => {
    let x = sx, y = sy;
    for (let i = 0; i < len; i++) {
      p.setOn(Math.round(x), Math.round(y), i % 5 < glow + 1 ? C.p5 : C.p3);
      y += 1; x += (noise1(i * 0.4, seed) - 0.5) * 2.2 + dirx * 0.25;
    }
  };
  vein(cx - 13, base - 30, 26, 1, -1); vein(cx + 14, base - 32, 28, 2, 1); vein(cx - 2, base - 20, 17, 3, 0);
  vein(cx - 20, base - 16, 12, 4, -1); vein(cx + 20, base - 14, 11, 5, 1);

  // shelf fungus and moss
  const shelf = (x, y, w) => { for (let i = 0; i < w; i++) { p.setOn(x + i, y, C.b7); p.setOn(x + i, y + 1, C.b5); } p.setOn(x + w, y, C.b6); };
  shelf(cx - 22, base - 24, 5); shelf(cx + 17, base - 12, 6); shelf(cx - 19, base - 9, 4);
  for (let dx = -26; dx <= 26; dx++) if (noise1(dx * 0.3, 21) > 0.6) for (let k = 0; k < 3; k++) p.setOn(cx + dx, base - 1 - k - (Math.abs(dx) < 20 ? 0 : 3), k === 2 ? C.g4 : C.g2);

  // the hollow face
  const eye = (ex, flip) => {
    const rows = eyeOpen === 2
      ? ['..LMML..', '.LM88ML.', 'LM8888ML', '.LM88ML.', '..LLLL..']
      : eyeOpen === 1
        ? ['........', '.LLMMLL.', 'LM8888ML', '.LLMMLL.', '........']
        : ['........', '........', 'KLLLLLLK', '........', '........'];
    rows.forEach((row, yy) => {
      for (let i = 0; i < 8; i++) {
        const ch = row[flip ? 7 - i : i];
        const x = ex + i, y = base - 40 + yy + Math.round((flip ? 7 - i : i) * -0.45) + 2;
        // dark socket behind
        p.setOn(x, y, C.ink);
        if (ch !== '.') p.setOn(x, y, U[ch]);
      }
    });
    // heavy brow
    for (let i = -1; i < 9; i++) { const y = base - 42 + Math.round((flip ? 7 - i : i) * -0.45) + 2; p.setOn(ex + i, y, BK[1]); p.setOn(ex + i, y - 1, BK[4]); }
  };
  eye(cx - 14, false); eye(cx + 6, true);
  // jagged maw
  for (let dx = -11; dx <= 11; dx++) {
    const top = base - 27 + Math.round(Math.abs(dx) * 0.25) + (Math.abs(dx) % 4 === 0 ? 2 : Math.abs(dx) % 4 === 2 ? -1 : 0);
    const bot = base - 18 - Math.round(Math.abs(dx) * 0.35) + (Math.abs(dx + 1) % 4 === 0 ? -2 : 0);
    for (let y = top; y <= bot; y++) {
      const inner = y - top > 1 && bot - y > 1 && Math.abs(dx) < 9;
      p.setOn(cx + dx, y, inner ? (glow && (dx + y) % 3 === 0 ? C.p4 : C.p2) : C.ink);
    }
    p.setOn(cx + dx, top - 1, BK[4]);
  }
  return p.outline(C.ink, 'ink', false);
}

function bossArm(seedN) {
  // a heavy root-arm, drawn pointing right from its shoulder; rotated in 5 poses by the game
  const out = [];
  const angles = [-1.15, -0.55, 0.05, 0.55, 0.95]; // raised ... slammed
  for (const a of angles) {
    const p = new Pix(64, 64), sx = 12, sy = 32;
    const len = 40;
    let px = sx, py = sy;
    for (let i = 0; i <= len; i++) {
      const t = i / len;
      const bend = a + Math.sin(t * 2.2) * 0.35;
      px += Math.cos(bend); py += Math.sin(bend);
      const th = t < 0.75 ? lerp(5, 3, t) : lerp(3, 6.5, (t - 0.75) / 0.25);
      for (let dy = -Math.round(th); dy <= Math.round(th); dy++) for (let dx = -Math.round(th); dx <= Math.round(th); dx++) {
        if (dx * dx + dy * dy > th * th + 0.5) continue;
        const l = (-dx * 0.5 - dy * 0.85) / (th + 0.5);
        let k = l > 0.45 ? 5 : l > 0 ? 4 : l > -0.5 ? 3 : 2;
        if (hash(Math.round(i / 3), Math.round(dy + 9), seedN) < 0.22) k--;
        p.set(Math.round(px + dx), Math.round(py + dy), BK[clamp(k, 1, 5)]);
      }
      if (i % 9 === 4) { p.setOn(Math.round(px), Math.round(py), C.p4); p.setOn(Math.round(px) + 1, Math.round(py) + 1, C.p3); }
    }
    // thorns on the club
    for (const [tx, ty] of [[4, -7], [8, 0], [4, 7], [-3, -8], [-3, 8]]) { p.line(px, py, px + tx, py + ty, BK[4], 1); p.set(Math.round(px + tx), Math.round(py + ty), C.p5); }
    out.push({ pix: p.outline(C.ink, 'ink', false), ox: sx, oy: sy, tip: [px - sx, py - sy] });
  }
  return out;
}

export const BOSS = {
  W: BOSS_W, H: BOSS_H,
  body: [bossBody(2, 0), bossBody(2, 1), bossBody(1, 0), bossBody(0, 0)],
  arms: bossArm(3),
};

// root spike that erupts from the ground (frames: telegraph crack -> full)
export const ROOT_SPIKE = [3, 9, 17, 24].map((h, i) => {
  const p = new Pix(14, 26);
  for (let j = 0; j < h; j++) {
    const t = j / h, hw = lerp(4.5, 0.4, Math.pow(t, 0.8));
    const cx = 7 + Math.sin(j * 0.35 + i) * 1.2;
    for (let dx = -Math.ceil(hw); dx <= Math.ceil(hw); dx++) {
      if (Math.abs(dx) > hw) continue;
      const u = (dx + hw) / (hw * 2 + 0.01);
      p.set(Math.round(cx + dx), 25 - j, u < 0.3 ? BK[5] : u < 0.7 ? BK[3] : BK[2]);
    }
    if (j % 6 === 3) p.setOn(Math.round(cx), 25 - j, C.p5);
  }
  return p.outline(C.ink, 'ink', false);
});

